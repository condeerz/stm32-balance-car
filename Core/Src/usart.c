/* printf 重定向到 USART3（VOFA+ 调试与串口打印共用） */
int fputc(int ch, FILE *f)
{
  uint8_t c = (uint8_t)ch;
  HAL_UART_Transmit(&huart3, &c, 1, 0xFFFF);
  return ch;
}

/* VOFA+ JustFloat 协议：n 个 float（小端 IEEE754）+ 4 字节帧尾 00 00 80 7F
   非阻塞发送：上一帧还没发完就丢弃本帧，避免在控制中断里长时间阻塞 */
void VOFA_SendFloats(const float *data, uint8_t n)
{
  static uint8_t buf[4 + 16 * 4];

  if (data == NULL || n == 0) return;
  if (n > 16) n = 16;
  if (huart3.gState != HAL_UART_STATE_READY) return;

  memcpy(buf, data, (uint32_t)n * sizeof(float));
  buf[n * 4 + 0] = 0x00;
  buf[n * 4 + 1] = 0x00;
  buf[n * 4 + 2] = 0x80;
  buf[n * 4 + 3] = 0x7F;
  HAL_UART_Transmit_IT(&huart3, buf, (uint16_t)(n * 4 + 4));
}
